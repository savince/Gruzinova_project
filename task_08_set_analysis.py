#Создаем множесва
set1 = set(["Эклер", "Корзиночка", "Наполеон", "Медовик", "Птичье молоко"])
set2 = set(["Корзиночка", "Наполеон", "Захер", "Эклер", "Прага"])
set3 = set(["Эклер", "Корзиночка", "Птичье молоко", "Тирамису", "Наполеон"])
# Все операции
print ("Все уникальные:", set1 | set2 | set3)
print ("Общие для всех:", set1 & set2 & set3)
print ("Только у первого:", set1 - set2 - set3)
print ("Ровно у двух:", (set1 & set2 - set3) | (set1 & set3 - set2) | (set2 & set3 - set1))